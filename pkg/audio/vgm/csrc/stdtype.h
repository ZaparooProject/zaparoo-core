// Fixed-width integer names and bool, which the vendored chip cores are
// written against.

#ifndef ZVGM_STDTYPE_H
#define ZVGM_STDTYPE_H

#include <stdbool.h>
#include <stdint.h>

typedef uint8_t UINT8;
typedef int8_t INT8;
typedef uint16_t UINT16;
typedef int16_t INT16;
typedef uint32_t UINT32;
typedef int32_t INT32;
typedef uint64_t UINT64;
typedef int64_t INT64;

#ifndef INLINE
#define INLINE static inline
#endif

#endif
