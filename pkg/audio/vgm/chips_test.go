func TestEveryChipStarts(t *testing.T) {
	t.Parallel()
	for _, tc := range chipCases {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			b := newVGM(0x171).clock(tc.typ, tc.clock)
			tc.setup(b)
			b.wait(oneSecond / 4)
			d := openTest(t, b.bytes(), Options{})
			require.GreaterOrEqual(t, d.handle[tc.typ][0], 0, "chip did not start")
			s := renderAll(t, d)
			require.Len(t, s, testRate/4)
			for _, f := range s {
				require.False(t, math.IsNaN(f[0]) || math.IsNaN(f[1]), "NaN output")
			}
			assert.Greater(t, rms(s), 0.01, "chip is silent")
			// Seeking back and forth is stable.
			require.NoError(t, d.Seek(100))
			again := renderN(t, d, 1000)
			assert.Equal(t, s[100:1100], again)
		})
	}
}

