// square8 is n bytes, the first half hi and the second half lo.
func square8(n int, hi, lo byte) []byte {
	return append(bytes.Repeat([]byte{hi}, n/2), bytes.Repeat([]byte{lo}, n-n/2)...)
}

func testROM(n int) []byte {
	rom := make([]byte, n)
	for i := range rom {
		rom[i] = byte(i*37) ^ byte(i>>5) //nolint:gosec // bounded test inputs
	}
	return rom
}

