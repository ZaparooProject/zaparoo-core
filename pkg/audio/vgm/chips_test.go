func TestExtraHeader(t *testing.T) {
	t.Parallel()
	// The second SN76489 gets its own clock and a volume from the extra
	// header: a different pitch and level from the first.
	b := snTone(1, 1)
	b.set32(0x0C, ntscClock|0x40000000)
	clk := uint32(ntscClock / 2)
	b.extra = []byte{
		0x0C, 0, 0, 0, // extra header length
		0x08, 0, 0, 0, // clock table at 4+8 = 12
		0x0A, 0, 0, 0, // volume table at 8+10 = 18
		1, chipSN76489, 0, 0, 0, 0, // chip 2 clock, set below
		1, chipSN76489, 1, 0x80, 0x80, // chip 2 at x0.5
	}
	binary.LittleEndian.PutUint32(b.extra[14:], clk)
	d := openTest(t, b.bytes(), Options{})
	s := renderAll(t, d)
	requirePitch(t, s[testRate/10:], testRate, 220.2, 0.02)
	require.Len(t, d.hdr.xVols, 1)
	assert.Equal(t, uint16(0x8080), d.hdr.xVols[0].vol)
}

func TestDecompressedStreamBlock(t *testing.T) {
	t.Parallel()
	// A bit-packed block (subtype 0, 4 bits in, 8 bits out, base 0x10) that
	// expands to the 1102.5 Hz square of TestYM2612DACDirect.
	const n = 4000
	payload := make([]byte, 0, 10+n/2)
	payload = append(payload, 0x00)
	payload = binary.LittleEndian.AppendUint32(payload, n)
	payload = append(payload, 8, 4, 0, 0x10, 0)
	for i := 0; i < n; i += 2 {
		hi, lo := byte(0), byte(0)
		if i%40 < 20 {
			hi = 0x0E
		}
		if (i+1)%40 < 20 {
			lo = 0x0E
		}
		payload = append(payload, hi<<4|lo)
	}
	b := newVGM(0x171).clock(chipYM2612, 7670453)
	b.dataBlock(0x40, payload)
	b.cmd(0x52, 0x2B, 0x80, 0x53, 0xB6, 0xC0, 0xE0, 0, 0, 0, 0)
	for range n {
		b.cmd(0x81)
		b.ticks++
	}
	d := openTest(t, b.bytes(), Options{})
	s := renderAll(t, d)
	requirePitch(t, s[testRate/100:], testRate, 1102.5, 0.03)
	assert.Len(t, d.st.banks[0].data, n)
}

func TestDecompressTable(t *testing.T) {
	t.Parallel()
	tables := decompTables{}
	// Table for bit-packing subtype 2 (table lookup), 8 bits out, 2 bits in.
	tables.addTable([]byte{0x00, 0x02, 8, 2, 4, 0, 10, 20, 30, 40})
	out, err := tables.decompress([]byte{0x00, 4, 0, 0, 0, 8, 2, 2, 0, 0, 0b00011011}, 1024)
	require.NoError(t, err)
	assert.Equal(t, []byte{10, 20, 30, 40}, out)

	// DPCM with the same table shape: running sum.
	tables.addTable([]byte{0x01, 0x00, 8, 2, 4, 0, 1, 2, 3, 4})
	out, err = tables.decompress([]byte{0x01, 4, 0, 0, 0, 8, 2, 0, 100, 0, 0b00011011}, 1024)
	require.NoError(t, err)
	assert.Equal(t, []byte{101, 103, 106, 110}, out)

	// 16-bit output, bc > 8 reads the low byte first.
	out, err = tables.decompress([]byte{0x00, 2, 0, 0, 0, 16, 12, 0, 0, 0, 0xAB, 0xC0}, 1024)
	require.NoError(t, err)
	assert.Len(t, out, 2)

	_, err = tables.decompress([]byte{0x00, 4, 0, 0, 0, 8, 2, 2, 0, 0, 0xFF}, 1024)
	require.NoError(t, err)
	_, err = tables.decompress([]byte{0x02, 4, 0, 0, 0, 8, 2, 0, 0, 0, 0xFF}, 1024)
	require.Error(t, err)
	_, err = decompTables{}.decompress([]byte{0x01, 4, 0, 0, 0, 8, 2, 0, 0, 0, 0xFF}, 1024)
	require.Error(t, err)
}
